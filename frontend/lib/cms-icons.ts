/** Lucide icon resolver for CMS JSON content. */
import {
  Award,
  BarChart3,
  Bell,
  Bird,
  Brain,
  Building2,
  FileCheck2,
  FileText,
  Globe2,
  Languages,
  Leaf,
  Lock,
  MapPin,
  Mic,
  Radar,
  Satellite,
  Scale,
  ScanLine,
  Shield,
  ShieldCheck,
  Smartphone,
  Sparkles,
  Sprout,
  TreePine,
  Trees,
  BadgeCheck,
  Users,
  type LucideIcon,
} from "lucide-react";

const ICONS: Record<string, LucideIcon> = {
  Award,
  BadgeCheck,
  BarChart3,
  Bell,
  Bird,
  Brain,
  Building2,
  FileCheck2,
  FileText,
  Globe2,
  Languages,
  Leaf,
  Lock,
  MapPin,
  Mic,
  Radar,
  Satellite,
  Scale,
  ScanLine,
  Shield,
  ShieldCheck,
  Smartphone,
  Sparkles,
  Sprout,
  TreePine,
  Trees,
  Users,
};

export function cmsIcon(name?: string): LucideIcon {
  if (!name) return Sparkles;
  return ICONS[name] ?? Sparkles;
}
